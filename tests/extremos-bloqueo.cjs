const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript')
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,f)
const {extremosBloqueo}=require('../lib/operacion/extremosBloqueo.ts')
const tramos=[{x1:1,y1:2,x2:2,y2:2},{x1:2,y1:2,x2:2,y2:3},{x1:2,y1:3,x2:2,y2:4}],copia=JSON.stringify(tramos)
assert.deepEqual(extremosBloqueo(tramos),[{x:1,y:2},{x:2,y:4}],'Only the two outer ends, not corners or unit segment boundaries')
assert.deepEqual(extremosBloqueo([...tramos,{x1:2,y1:2,x2:1,y2:2}]),[{x:1,y:2},{x:2,y:4}],'Duplicate reversed edges do not remove endpoints')
assert.equal(extremosBloqueo([...tramos,{x1:9,y1:9,x2:10,y2:9}]).length,4,'Disconnected lines keep their own endpoints')
assert.deepEqual(extremosBloqueo([]),[])
assert.deepEqual(extremosBloqueo([{x1:1,y1:1,x2:1,y2:1}]),[])
assert.equal(JSON.stringify(tramos),copia,'Coordinates remain unchanged')
console.log('Block warning endpoints: straight lines, turns, duplicates and disconnected lines OK')
