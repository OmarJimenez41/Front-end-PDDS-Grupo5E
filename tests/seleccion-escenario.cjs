const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript')
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,f)
const {escenarioParaMapa}=require('../lib/operacion/seleccionEscenario.ts')
assert.equal(escenarioParaMapa(null,null,9,true),null,'Draft/start request must not read daily data')
assert.equal(escenarioParaMapa(17,null,9,false),17,'New simulation uses its own scenario')
assert.equal(escenarioParaMapa(null,16,9,true),16,'Explicit shared scenario stays selected')
assert.equal(escenarioParaMapa(null,null,9,false),9,'Returning to daily restores its scenario')
const {estacionadaEnAlmacen}=require('../lib/operacion/agrupacionMapa.ts')
const bases=[{x:27,y:14}],v={id:1,x:27,y:14,estado:'EN_BASE'}
assert.equal(estacionadaEnAlmacen(v,bases),true)
assert.equal(estacionadaEnAlmacen({...v,estado:'PROGRAMADA'},bases),true)
assert.equal(estacionadaEnAlmacen({...v,estado:'EN_RUTA'},bases),false,'Departure remains visible at warehouse')
assert.equal(estacionadaEnAlmacen({...v,estado:'AVERIADA'},bases),false,'An incident must stay visible')
assert.equal(estacionadaEnAlmacen({...v,x:28},bases),false)
assert.deepEqual(v,{id:1,x:27,y:14,estado:'EN_BASE'},'Never move physical coordinates')
console.log('Independent draft selection and parked warehouse markers: OK')

const {escenarioPorTipo}=require('../lib/operacion/seleccionEscenario.ts')
assert.equal(escenarioPorTipo('CINCO_DIAS','day'),'five','Shared scenario determines active navigation')
assert.equal(escenarioPorTipo('COLAPSO','day'),'collapse')
assert.equal(escenarioPorTipo('DIA_A_DIA','five'),'day')
assert.equal(escenarioPorTipo(undefined,'five'),'five','An empty draft preserves explicit user selection')
